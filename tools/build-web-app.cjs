/* Publish the shared life-wheel UI with the English copy and web platform adapter. */
const fs = require('node:fs');
const path = require('node:path');
const {createHash} = require('node:crypto');

const root = path.resolve(__dirname, '..');
const source = path.join(root, 'app/src/main/assets/web');
const target = path.join(root, 'docs/web-app');
const read = filename => fs.readFileSync(filename, 'utf8').replace(/\r\n/g, '\n');

function replaceRequired(text, pattern, replacement) {
  const result = text.replace(pattern, replacement);
  if (result === text) throw new Error('Could not find the shared web source section: ' + pattern);
  return result;
}

const generated = '/* Generated by tools/build-web-app.cjs. */\n';
let ui = read(path.join(source, 'app.js'));
ui = replaceRequired(ui, /^    es: \{\n[\s\S]*?^    \},\n(?=    en:)/m, '');
ui = replaceRequired(ui, /^    const languageOptions = .*;\n/m, '');
ui = replaceRequired(ui, "+(web?'':languageOptions)+", '+');
ui = replaceRequired(ui, /state.locale === 'es' \? '[^']*' : 'Main navigation'/, "'Main navigation'");

const model = replaceRequired(read(path.join(source, 'core.js')), /, es: '[^']*'/g, '');
fs.writeFileSync(path.join(target, 'app.js'), generated + ui);
fs.writeFileSync(path.join(target, 'core.js'), generated + model);
fs.writeFileSync(path.join(target, 'style.css'), generated + read(path.join(source, 'style.css')));
fs.copyFileSync(path.join(root, 'ios/Brujula/Assets.xcassets/AppIcon.appiconset/AppIcon.png'), path.join(target, 'icon.png'));

const assets = ['index.html', 'app.js', 'core.js', 'style.css', 'install.css', 'web-platform.js', 'manifest.webmanifest', 'icon.png'];
const hash = createHash('sha256');
for (const name of assets) {
  hash.update(name);
  hash.update(name.endsWith('.png') ? fs.readFileSync(path.join(target, name)) : read(path.join(target, name)));
}
const revision = hash.digest('hex').slice(0, 16);

fs.writeFileSync(path.join(target, 'service-worker.js'), generated + `'use strict';

const prefix = 'brujula-web-';
const cacheName = prefix + '${revision}';
const assets = ${JSON.stringify(assets)};
const scope = self.registration.scope;

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(cacheName);
    await cache.addAll(assets.map(asset => new Request(new URL(asset, scope), {cache: 'reload'})));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter(name => name.startsWith(prefix) && name !== cacheName).map(name => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  url.search = '';
  const path = url.href === scope ? 'index.html' : url.href.slice(scope.length);
  if (!url.href.startsWith(scope) || !assets.includes(path)) return;

  event.respondWith((async () => {
    const cache = await caches.open(cacheName);
    return (await cache.match(new URL(path, scope))) || fetch(event.request);
  })());
});
`);
